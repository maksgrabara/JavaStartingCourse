package Introduction;

public class RelationalOperators {
    public static void main(String[] args){

        boolean output;
        output = 8 == 8;
        System.out.println("8 == 8: " + output);

        output = 3 == 8;
        System.out.println("3 == 8: " + output);

        output = 3 != 8;
        System.out.println("3 != 8: " + output);
    }
}
