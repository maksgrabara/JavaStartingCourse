package Introduction;

public class AritmeticOperators {
    public static void main(String[] args){

        System.out.println(10 % 4);

        double a = 9, b = 5.5;

        System.out.println(a % b);

        a += b;

        System.out.println(a);

        a -= b;

        System.out.println(a);

        a %= b;

        System.out.println(a);
    }
}
